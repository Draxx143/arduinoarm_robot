#!/bin/bash
# ============================================================
# AXIS-5 Robot Control — deb after-install script (v1.0.5+)
# - Dynamically locates the app binary (any /opt/* install dir)
# - Setuids the Chrome sandbox helper (belt & braces)
# - Installs /usr/bin/axis5-robot-control wrapper: passes
#   --no-sandbox (Ubuntu 23.10+/24.04+ AppArmor user-namespace
#   restrictions) and logs every run to ~/.axis5/last-run.log
# - Points the .desktop launcher(s) at the wrapper so menu
#   launches get the same treatment
# Prints diagnostics to stderr so `apt install` output shows
# exactly what happened.
# ============================================================

APP_BIN=""
for cand in /opt/*/axis5-robot-control /opt/*/AXIS5-Robot-Control/axis5-robot-control; do
  if [ -x "$cand" ]; then
    APP_BIN="$cand"
    break
  fi
done

echo "[axis5-after-install] located binary: ${APP_BIN:-<NOT FOUND>}" >&2

if [ -n "$APP_BIN" ]; then
  APP_DIR="$(dirname "$APP_BIN")"

  if [ -e "$APP_DIR/chrome-sandbox" ]; then
    chmod 4755 "$APP_DIR/chrome-sandbox" 2>/dev/null || true
  fi

  # ---- wrapper launcher ----
  rm -f /usr/bin/axis5-robot-control
  {
    echo '#!/bin/bash'
    echo '# AXIS-5 Robot Control launcher (generated by package post-install)'
    echo 'LOG_DIR="$HOME/.axis5"'
    echo 'mkdir -p "$LOG_DIR" 2>/dev/null'
    echo 'LOG_FILE="$LOG_DIR/last-run.log"'
    echo 'echo "=== AXIS-5 launch $(date) | args: $* | session: ${XDG_SESSION_TYPE:-unknown} ===" >> "$LOG_FILE" 2>/dev/null'
    echo 'export ELECTRON_DISABLE_SANDBOX=1'
    echo "\"$APP_BIN\" --no-sandbox --disable-gpu-sandbox \"\$@\" 2>&1 | tee -a \"\$LOG_FILE\""
    echo 'exit ${PIPESTATUS[0]}'
  } > /usr/bin/axis5-robot-control
  chmod 755 /usr/bin/axis5-robot-control 2>/dev/null || true
  echo "[axis5-after-install] wrapper installed: /usr/bin/axis5-robot-control -> $APP_BIN" >&2

  # ---- free the serial port from ModemManager / brltty -----------------
  # ModemManager probes every new tty with AT commands and toggles DTR (which
  # resets the Arduino and eats its first bytes); brltty claims the CH340 chip
  # (1a86:7523) as a braille display and makes the port busy. Symptom: pressing
  # Connect stiffens the motors but the app never receives a single byte.
  RULE_SRC=""
  for cand in "$APP_DIR/99-axis5-serial.rules" /opt/*/99-axis5-serial.rules; do
    [ -f "$cand" ] && { RULE_SRC="$cand"; break; }
  done
  if [ -n "$RULE_SRC" ]; then
    install -m 0644 "$RULE_SRC" /etc/udev/rules.d/99-axis5-serial.rules 2>/dev/null \
      && echo "[axis5-after-install] udev rule installed: /etc/udev/rules.d/99-axis5-serial.rules" >&2 \
      || echo "[axis5-after-install] WARNING: could not install the udev rule" >&2
    # A file in /etc/udev/rules.d overrides the same-named file in /lib: keep
    # brltty but drop its CH340 (1a86) claim — no package removal needed.
    for b in /lib/udev/rules.d/85-brltty.rules /usr/lib/udev/rules.d/85-brltty.rules; do
      [ -f "$b" ] || continue
      grep -qi '1a86' "$b" || continue
      sed -E '/1a86/ s/^/#AXIS5: /' "$b" > /tmp/85-brltty.rules.axis5 2>/dev/null \
        && install -m 0644 /tmp/85-brltty.rules.axis5 /etc/udev/rules.d/85-brltty.rules 2>/dev/null \
        && echo "[axis5-after-install] brltty no longer claims CH340 (1a86)" >&2
      rm -f /tmp/85-brltty.rules.axis5
      break
    done
    udevadm control --reload >/dev/null 2>&1 || true
    udevadm trigger --subsystem-match=tty >/dev/null 2>&1 || true
    echo "[axis5-after-install] udev reloaded — replug the board once to get /dev/axis5" >&2
  else
    echo "[axis5-after-install] WARNING: 99-axis5-serial.rules not found in the package" >&2
  fi

  # ---- point desktop entries at the wrapper ----
  for f in /usr/share/applications/*.desktop; do
    [ -f "$f" ] || continue
    if grep -qi "axis5" "$f" 2>/dev/null; then
      sed -i 's|^Exec=.*|Exec=/usr/bin/axis5-robot-control %U|' "$f" || true
      echo "[axis5-after-install] desktop entry patched: $f" >&2
    fi
  done
else
  echo "[axis5-after-install] WARNING: app binary not found — launcher not created" >&2
fi

if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database /usr/share/applications >/dev/null 2>&1 || true
fi

if command -v gtk-update-icon-cache >/dev/null 2>&1; then
  gtk-update-icon-cache -f -t /usr/share/icons/hicolor >/dev/null 2>&1 || true
fi

exit 0
